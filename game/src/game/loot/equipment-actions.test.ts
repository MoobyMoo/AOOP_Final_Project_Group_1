import { G, V, type Enemy } from "../core/state";
import { migrate } from "../core/save";
import { BOUND_KIT, gearStats, repairCost } from "./equipment";
import { collectEquipment, drainEquipmentEvents, equipFromLocker, equipFromPack, heardEnemies, interruptEquip, loseWornEquipment, protectPlayerHit, refreshEquipment, repair, repairAll, restoreBoundKit, sellEquip, stash, unequip, updateEquipment } from "./equipment-actions";

let checks = 0;
function assert(ok: boolean, message: string) {
  checks++;
  if (!ok) throw new Error(message);
}
function resetState() {
  G.save = migrate(null); G.gear = { ...BOUND_KIT }; G.pack = []; G.scene = "raid"; G.alive = true;
  G.rollT = -1; G.useItem = null; G.zipping = null; G.equipping = null; G.equipmentEvents = [];
  refreshEquipment();
}
resetState();
assert(collectEquipment("hardhat#73") === "packed" && G.gear.head === "bowler", "pickup does not replace bound gear");
assert(equipFromPack(0), "start a pack equip");
updateEquipment(0.99);
assert(G.gear.head === "bowler" && G.pack.length === 1, "one second equip, no early mutation");
interruptEquip(); updateEquipment(2);
assert(G.pack[0] === "hardhat#73" && G.gear.head === "bowler", "interruption conserves item and starter");
assert(equipFromPack(0), "retry equip"); updateEquipment(1);
assert(G.gear.head === "hardhat#73" && G.pack.length === 0 && G.save.locker.includes("bowler"), "bound replacement returns home");
G.pack = ["pot_helmet#37"];
assert(equipFromPack(0), "swap non-bound gear"); updateEquipment(1);
assert(G.gear.head === "pot_helmet#37" && G.pack[0] === "hardhat#73", "swap preserves both conditions");
G.pack = ["leaf_vest"];
assert(equipFromPack(0), "start body equip");
assert(protectPlayerHit(12, false) === 12 && G.equipping === null && G.pack[0] === "leaf_vest", "hit interrupts before equipment change");
G.gear = { ...BOUND_KIT, head: "hardhat#1", face: "goggles#1", body: "warden_vest#1" };
const headArmor = gearStats(G.gear).headArmor;
assert(protectPlayerHit(18, true) === Math.round(18 * 2 / (headArmor + 2)), "critical uses combined head armor before breaking");
assert(G.gear.head === "hardhat#0" && G.gear.face === "goggles#0" && G.gear.body === "warden_vest#1", "critical wears both protective head pieces only");
assert(drainEquipmentEvents().some(event => event.message === "Helmet cracked!"), "HUD break event");
assert(protectPlayerHit(18, false) === 6 && G.gear.body === "warden_vest#0", "body armor protects breaking hit");
assert(protectPlayerHit(18, false) === 18, "broken body no longer protects");
resetState();
G.gear.ears = null;
assert(collectEquipment("walkman") === "equipping", "empty slot auto-equip uses the same timer");
updateEquipment(1);
assert(G.gear.ears === "walkman" && G.pack.length === 0, "empty slot equipment completes");
G.gear.back = "bigpack"; refreshEquipment(); G.pack = Array(9).fill("banana");
assert(G.packSlots === 10 && !unequip("back"), "capacity-reducing unequip cannot delete overflow");
G.pack = [];
assert(unequip("back"), "unequip non-bound backpack"); updateEquipment(1);
assert(G.pack[0] === "bigpack" && G.gear.back === null && G.packSlots === 8, "unequip occupies one pack slot");
resetState(); G.gear.head = "hardhat#42";
const lost = loseWornEquipment();
assert(lost.length === 1 && lost[0] === "hardhat#42" && G.gear.face === "shades" && G.gear.body === "suit", "death transfers found worn gear and retains bound pieces");
G.save.locker.push("bowler"); restoreBoundKit();
assert(G.gear.head === "bowler" && !G.save.locker.includes("bowler"), "home starter restored without duplication");
assert(!equipFromLocker(0) && !repair("face") && !stash(0) && sellEquip(0) === 0 && repairAll() === 0, "home APIs reject raid calls");
G.scene = "bunker"; G.save.gear = { ...G.gear }; G.save.locker = ["hardhat#50", "hardhat#50"];
assert(equipFromLocker(1) && G.save.gear.head === "hardhat#50" && G.save.locker.includes("hardhat#50"), "locker indices distinguish identical instances");
G.save.money = 0;
assert(!repair("head") && G.save.gear.head === "hardhat#50", "unaffordable repair is atomic");
G.save.money = 100; const cost = repairCost("hardhat#50");
assert(repair("head") && G.save.money === 100 - cost && G.save.gear.head === "hardhat", "slot repair deducts exact cost");
const saleIndex = G.save.locker.indexOf("hardhat#50"), beforeSale = G.save.money;
assert(sellEquip(saleIndex) === 30 && G.save.money === beforeSale + 30, "condition-scaled sale");
const boundIndex = G.save.locker.indexOf("bowler"), count = G.save.locker.length;
assert(sellEquip(boundIndex) === 0 && G.save.locker.length === count, "bound starter cannot be sold");
G.pack = ["leaf_vest#60"]; assert(stash(0) && !G.pack.length && G.save.locker.includes("leaf_vest#60"), "stash moves instance into locker");
G.save.money = 0; assert(repairAll() === 0 && G.save.locker.includes("leaf_vest#60"), "repair-all checks total affordability");
G.save.money = 1000; assert(repairAll() === repairCost("leaf_vest#60") && G.save.locker.includes("leaf_vest"), "repair-all includes locker");
assert(unequip("body") && G.save.gear.body === null && migrate(G.save).gear.body === null, "empty modern body slot survives migration");
G.scene = "raid"; G.gear.ears = "walkman"; G.pp = V(0, 0);
G.enemies = [{ id: 1, p: V(17, 0), vel: V(1, 0), down: false }, { id: 2, p: V(19, 0), vel: V(1, 0), down: false }, { id: 3, p: V(1, 0), vel: V(0, 0), down: false }, { id: 4, p: V(1, 0), vel: V(1, 0), down: true }] as Enemy[];
assert(heardEnemies().length === 1 && heardEnemies()[0].id === 1, "hearing reports only moving living enemies in range");
G.scene = "bunker"; assert(!heardEnemies().length, "no stale hearing markers at home");
resetState();
console.log(`Equipment actions self-test: PASS (${checks} checks)`);
